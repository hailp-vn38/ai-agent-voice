import { describe, expect, it } from 'vitest'
import { router } from './index'

describe('Agent Job detail routing', () => {
  it('resolves Job details as a distinct page from the Jobs list', () => {
    const list = router.resolve('/jobs')
    const detail = router.resolve('/jobs/job-2847')
    expect(list.name).toBe('jobs')
    expect(detail.name).toBe('job-detail')
    expect(detail.params.jobId).toBe('job-2847')
  })

  it('uses dedicated Jobs settings hub and sub-page routes without an Agent permission route', () => {
    expect(router.resolve('/jobs/settings').name).toBe('jobs-settings')
    expect(router.resolve('/jobs/settings/runtime').name).toBe('jobs-settings-runtime')
    expect(router.resolve('/jobs/settings/providers').name).toBe('jobs-settings-providers')
    expect(router.resolve('/jobs/settings/agents').name).toBe('jobs-settings-agents')
    expect(router.resolve('/jobs/settings/skills').name).toBe('jobs-settings-skills')
    expect(router.resolve('/jobs/settings/skills/new').name).toBe('jobs-settings-skill-create')
    const skillRoute = router.resolve('/jobs/settings/skills/wiki-query')
    expect(skillRoute.name).toBe('jobs-settings-skill')
    expect(skillRoute.params.skillId).toBe('wiki-query')
    const subagentRoute = router.resolve('/jobs/settings/agents/wiki_researcher')
    expect(subagentRoute.name).toBe('jobs-settings-agent')
    expect(subagentRoute.params.agentId).toBe('wiki_researcher')
    expect(router.resolve('/agents/demo-agent').name).toBe('agent-detail')
  })

  it('resolves System Hub and dedicated System sub-page routes', () => {
    expect(router.resolve('/system').name).toBe('system')
    expect(router.resolve('/system/monitor').name).toBe('system-monitor')
    expect(router.resolve('/system/resources').name).toBe('system-monitor')
    expect(router.resolve('/system/runtime').name).toBe('system-runtime')
    expect(router.resolve('/system/assistant').name).toBe('system-assistant')
    expect(router.resolve('/system/backup').name).toBe('system-backup')
    expect(router.resolve('/system/transport').name).toBe('system-transport')
    expect(router.resolve('/system/mcp').name).toBe('system-mcp')
    expect(router.resolve('/system/notifications').name).toBe('system-notifications')
    expect(router.resolve('/system/logs').name).toBe('system-logs')
  })

  it('resolves LLM Gateway Hub and dedicated LLM Gateway sub-page routes', () => {
    expect(router.resolve('/llm-gateway').name).toBe('llm-gateway')
    expect(router.resolve('/llm-gateway/pools').name).toBe('llm-gateway-pools')
    const poolRoute = router.resolve('/llm-gateway/pools/openai_codex')
    expect(poolRoute.name).toBe('llm-gateway-pool')
    expect(poolRoute.params.vendor).toBe('openai_codex')
    expect(router.resolve('/llm-gateway/accounts').name).toBe('llm-gateway-accounts')
    const accountRoute = router.resolve('/llm-gateway/accounts/gw_openai_codex_145ef96e')
    expect(accountRoute.name).toBe('llm-gateway-account')
    expect(accountRoute.params.accountKey).toBe('gw_openai_codex_145ef96e')
    expect(router.resolve('/llm-gateway/models').name).toBe('llm-gateway-models')
    expect(router.resolve('/llm-gateway/models/new').name).toBe('llm-gateway-model-create')
    const modelRoute = router.resolve('/llm-gateway/models/llm_codex_pool_1')
    expect(modelRoute.name).toBe('llm-gateway-model')
    expect(modelRoute.params.providerKey).toBe('llm_codex_pool_1')
    expect(router.resolve('/llm-gateway/quotas').name).toBe('llm-gateway-quotas')
    expect(router.resolve('/llm-gateway/connect').name).toBe('llm-gateway-connect')
  })
})
